
import React, { useState } from 'react';
import { MOCK_CASES } from '../constants';
import { CaseStatus } from '../types';
import { generatePDF } from '../utils/reportGenerator';

const AssetRegistry: React.FC = () => {
  const [filter, setFilter] = useState<string>('All');
  const [searchTerm, setSearchTerm] = useState<string>('');

  const filteredCases = MOCK_CASES.filter(c => {
    const matchesFilter = filter === 'All' || c.status === filter;
    const matchesSearch = c.device.toLowerCase().includes(searchTerm.toLowerCase()) || 
                          c.id.toLowerCase().includes(searchTerm.toLowerCase()) ||
                          c.owner.toLowerCase().includes(searchTerm.toLowerCase());
    return matchesFilter && matchesSearch;
  });

  const getStatusColor = (status: CaseStatus) => {
    switch (status) {
      case CaseStatus.Active: return 'bg-red-500/20 text-red-400 border-red-500/50';
      case CaseStatus.Pending: return 'bg-yellow-500/20 text-yellow-400 border-yellow-500/50';
      case CaseStatus.Recovered: return 'bg-green-500/20 text-green-400 border-green-500/50';
      default: return 'bg-gray-500/20 text-gray-400 border-gray-500/50';
    }
  };

  return (
    <div id="asset-registry-report" className="space-y-6 h-full flex flex-col">
        <div className="pdf-watermark">
            <h1 className="text-2xl font-bold text-black uppercase">Asset Registry List</h1>
            <p className="text-sm text-gray-600">Generated by K-DART System</p>
        </div>
        <div className="flex justify-between items-end">
            <div>
                <h2 className="text-2xl font-black text-white uppercase tracking-wider mb-2">Central Asset Registry</h2>
                <p className="text-brand-text-secondary text-sm">National Database / Authorized Access Level 4</p>
            </div>
            <div className="flex space-x-3">
                 <button 
                    onClick={() => generatePDF('asset-registry-report', `K-DART_Registry_${Date.now()}.pdf`)}
                    className="bg-brand-secondary border border-brand-light hover:bg-white hover:text-black text-white px-4 py-2 rounded text-sm font-bold uppercase tracking-wide transition-colors flex items-center no-print"
                >
                     <svg className="w-4 h-4 mr-2" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4"></path></svg>
                    Download List
                </button>
                <button className="bg-brand-accent hover:bg-blue-600 text-white px-4 py-2 rounded text-sm font-bold uppercase tracking-wide transition-colors no-print">
                    + Register New Case
                </button>
            </div>
        </div>

        <div className="bg-brand-secondary p-4 rounded-lg border border-brand-light flex gap-4 items-center no-print">
            <div className="relative flex-1">
                <input 
                    type="text" 
                    placeholder="Search by ID, Device, or Owner Name..." 
                    className="w-full bg-brand-dark border border-brand-light rounded py-2 px-4 text-white focus:border-brand-accent focus:outline-none"
                    value={searchTerm}
                    onChange={(e) => setSearchTerm(e.target.value)}
                />
            </div>
            <select 
                className="bg-brand-dark border border-brand-light rounded py-2 px-4 text-white focus:border-brand-accent focus:outline-none"
                value={filter}
                onChange={(e) => setFilter(e.target.value)}
            >
                <option value="All">All Statuses</option>
                <option value="Active">Active</option>
                <option value="Pending">Pending</option>
                <option value="Recovered">Recovered</option>
            </select>
        </div>

        <div className="bg-brand-secondary rounded-lg border border-brand-light flex-1 overflow-hidden flex flex-col">
            <div className="overflow-x-auto">
                <table className="w-full text-left">
                    <thead className="bg-brand-dark/50">
                        <tr>
                            <th className="py-3 px-6 text-xs font-bold text-brand-text-secondary uppercase">Case ID</th>
                            <th className="py-3 px-6 text-xs font-bold text-brand-text-secondary uppercase">Device Info</th>
                            <th className="py-3 px-6 text-xs font-bold text-brand-text-secondary uppercase">Owner</th>
                            <th className="py-3 px-6 text-xs font-bold text-brand-text-secondary uppercase">Last Location</th>
                            <th className="py-3 px-6 text-xs font-bold text-brand-text-secondary uppercase">Status</th>
                            <th className="py-3 px-6 text-xs font-bold text-brand-text-secondary uppercase no-print">Actions</th>
                        </tr>
                    </thead>
                    <tbody className="divide-y divide-brand-light/30">
                        {filteredCases.map((c) => (
                            <tr key={c.id} className="hover:bg-brand-light/10 transition-colors">
                                <td className="py-4 px-6 text-brand-accent font-mono text-sm">{c.id}</td>
                                <td className="py-4 px-6">
                                    <div className="font-bold text-white">{c.device}</div>
                                    <div className="text-xs text-brand-text-secondary">{c.type}</div>
                                </td>
                                <td className="py-4 px-6 text-sm text-brand-text">{c.owner}</td>
                                <td className="py-4 px-6 text-sm text-brand-text-secondary">{c.location}</td>
                                <td className="py-4 px-6">
                                    <span className={`px-2 py-1 rounded text-xs font-bold uppercase border ${getStatusColor(c.status)}`}>
                                        {c.status}
                                    </span>
                                </td>
                                <td className="py-4 px-6 no-print">
                                    <button className="text-brand-accent hover:text-white text-xs font-bold uppercase mr-3">Details</button>
                                    <button className="text-brand-text-secondary hover:text-white text-xs uppercase">Edit</button>
                                </td>
                            </tr>
                        ))}
                    </tbody>
                </table>
            </div>
            {filteredCases.length === 0 && (
                <div className="flex-1 flex items-center justify-center text-brand-text-secondary opacity-50">
                    No records found matching criteria.
                </div>
            )}
        </div>
    </div>
  );
};

export default AssetRegistry;
